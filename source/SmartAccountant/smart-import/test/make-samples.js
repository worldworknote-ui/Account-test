const serial = (y, m, d) => (Date.UTC(y, m - 1, d) - Date.UTC(1899, 11, 30)) / 86400000;
const D = (y, m, d) => ({ __date: serial(y, m, d) });
const F = (f, v) => ({ __f: f, v: v });

/** صفوف ← ورقة: التواريخ أرقام Excel بتنسيق تاريخ، والمعادلات بقيمتها المحفوظة. */
function sheet(rows) {
  const plain = rows.map((r) => r.map((v) => (v && typeof v === "object" ? null : v)));
  const ws = XLSX.utils.aoa_to_sheet(plain);
  rows.forEach((r, ri) => r.forEach((v, ci) => {
    if (!v || typeof v !== "object") return;
    const a = XLSX.utils.encode_cell({ r: ri, c: ci });
    if (v.__date !== undefined) ws[a] = { t: "n", v: v.__date, z: "dd/mm/yyyy" };
    else if (v.__f !== undefined) ws[a] = { t: typeof v.v === "number" ? "n" : "s", v: v.v, f: v.__f };
  }));
  const rg = XLSX.utils.decode_range(ws["!ref"]);
  rows.forEach((r, ri) => { rg.e.r = Math.max(rg.e.r, ri); rg.e.c = Math.max(rg.e.c, r.length - 1); });
  ws["!ref"] = XLSX.utils.encode_range(rg);
  return ws;
}
function save(name, sheets) {
  const wb = XLSX.utils.book_new();
  sheets.forEach(([n, rows]) => XLSX.utils.book_append_sheet(wb, sheet(rows), n));
  fs.writeFileSync(path.join(out, name), Buffer.from(XLSX.write(wb, { type: "array", bookType: "xlsx" })));
}

