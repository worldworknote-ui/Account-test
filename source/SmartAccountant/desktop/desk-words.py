#!/usr/bin/env python3
"""11.2: نسخة الكمبيوتر تقول «الكمبيوتر/الجهاز» بدل «الهاتف» في نصوص البرنامج نفسها.

يعمل عند البناء فقط وعلى نسخة من ملفات تطبيق الهاتف (لا يغيّر ملفات أندرويد)، وداخل النصوص الثابتة في الكود فقط،
فلا يمس بيانات المستخدم أبدًا (ملاحظة فيها «الهاتف» تبقى كما هي).
لا يغيّر: أرقام الهواتف ("رقم الهاتف"، "هاتف المكتب")، والنصوص التي تشرح أجهزة متعددة (فيها الماك أو الويندوز أو أندرويد)،
وملفات قراءة رسائل الحوالات (كلماتها للمطابقة لا للعرض).

الاستعمال: desk-words.py <مجلد ملفات الهاتف> <مجلد الناتج>
"""
import os
import re
import sys

SKIP_FILES = {"MessageParser.java", "SyncHelp.java"}
SKIP_IF = ["الماك", "ماك", "الويندوز", "ويندوز", "أندرويد", "الكمبيوتر", "رقم الهاتف", "هاتف المكتب", "تلفون", "تليفون", "phone"]
# عبارات محددة فقط (كلمة «الهاتف» وحدها قد تعني رقم الهاتف فتبقى كما هي)
RULES = [
    ("بالبصمة أو بقفل الشاشة", "ببصمة الجهاز أو كلمة سره"),
    ("قفل شاشة الهاتف", "كلمة سر الجهاز"),
    ("بلا بصمة ولا قفل شاشة", "بلا بصمة ولا كلمة سر للجهاز"),
    ("ولا قفل شاشة", "ولا كلمة سر للجهاز"),
    ("أو قفل الشاشة", "أو كلمة سر الجهاز"),
    ("قفل الشاشة", "كلمة سر الجهاز"),
    ("إعدادات الهاتف", "إعدادات النظام"),
    ("هذا الهاتف", "هذا الكمبيوتر"),
    ("هاتفك", "جهازك"),
    ("هاتفًا آخر", "جهازًا آخر"),
    ("هاتف آخر", "جهاز آخر"),
    ("هاتف جديد", "جهاز جديد"),
    ("حسب الهاتف", "حسب الجهاز"),
    ("خط الهاتف", "خط النظام"),
    ("ذاكرة الهاتف", "ذاكرة الكمبيوتر"),
    ("خارج الهاتف", "خارج الكمبيوتر"),
    ("عن الهاتف", "عن الكمبيوتر"),
    ("داخل الهاتف", "داخل الكمبيوتر"),
    ("في الهاتف", "في الكمبيوتر"),
    ("على الهاتف", "على الكمبيوتر"),
    ("من الهاتف", "من الكمبيوتر"),
    ("ضاع الهاتف", "ضاع الكمبيوتر"),
    ("حامل الهاتف", "حامل الكمبيوتر"),
    ("يحمل الهاتف", "يحمل الكمبيوتر"),
    ("يفتح الهاتف", "يفتح الكمبيوتر"),
    ("بصمة الهاتف", "بصمة الكمبيوتر"),
    ("مفتاح الهاتف", "مفتاح الكمبيوتر"),
    ("يرسل الهاتف", "يرسل الكمبيوتر"),
    ("الهاتف الأصلي", "الجهاز الأصلي"),
    ("الهاتف القديم", "الجهاز القديم"),
    ("الهاتف الجديد", "الجهاز الجديد"),
    ("الهاتف وحده", "الكمبيوتر وحده"),
    ("الهاتف وقفله", "الكمبيوتر وقفله"),
    ("الهاتف بلا بصمة", "الكمبيوتر بلا بصمة"),
]
LIT = re.compile(r'"(?:[^"\\\n]|\\.)*"')


def fix(lit):
    if not any(w in lit for w in ("هاتف", "قفل شاشة", "قفل الشاشة")):
        return lit
    if any(w in lit for w in SKIP_IF):
        return lit
    # تسمية رقم الهاتف قبل قيمته: "...الهاتف: " + phone
    if lit.rstrip('"').rstrip().endswith("الهاتف:"):
        return lit
    for a, b in RULES:
        lit = lit.replace(a, b)
    return lit


def main():
    src, out = sys.argv[1], sys.argv[2]
    os.makedirs(out, exist_ok=True)
    changed = 0
    for n in sorted(os.listdir(src)):
        if not n.endswith(".java"):
            continue
        s = open(os.path.join(src, n), encoding="utf-8").read()
        t = s if n in SKIP_FILES else LIT.sub(lambda m: fix(m.group(0)), s)
        if t != s:
            changed += 1
        open(os.path.join(out, n), "w", encoding="utf-8").write(t)
    print("desk-words: %d files adjusted" % changed)


if __name__ == "__main__":
    main()
